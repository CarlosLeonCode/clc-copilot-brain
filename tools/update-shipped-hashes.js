#!/usr/bin/env node
/**
 * Shipped-Hashes Generator
 * Writes src/core/shipped-hashes.js: for every template-owned file `clc-brain upgrade` manages, the SHA-256
 * (CRLF normalized to LF) of every version this repository ever committed, plus the working-tree version.
 * `upgrade` replaces a brain file only when its hash is listed (an untouched copy); edited files are kept.
 *
 * Run after changing any template-owned file (tests/shipped-hashes.test.js fails until you do):
 *   node tools/update-shipped-hashes.js
 *
 * Brain path -> repository paths it was shipped from (current and earlier locations):
 *   .agents/skills/<name>/SKILL.md   templates/base/.agents/skills/<name>/SKILL.md, templates/base/.agents/skills/<name>.md,
 *                                    .agents/skills/<name>/SKILL.md, .agents/skills/<name>.md (flat skills become folders)
 *   skills/<file>.md                 templates/base/skills/<file>.md, skills/<file>.md
 *   sales/qualification/qualification-matrix.md   templates/areas/... and templates/locales/<lang>/areas/...
 * Self-contained: uses only Node.js built-ins and git.
 */
const { execFileSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const OUT = path.join(REPO_ROOT, 'src', 'core', 'shipped-hashes.js');
const MATRIX = 'sales/qualification/qualification-matrix.md';

const hash = (text) => crypto.createHash('sha256').update(String(text).replace(/\r\n/g, '\n'), 'utf8').digest('hex');
const git = (args) => execFileSync('git', args, { cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });

function listDirs(rel) {
  const abs = path.join(REPO_ROOT, rel);
  return fs.existsSync(abs) ? fs.readdirSync(abs, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort() : [];
}

function listMd(rel) {
  const abs = path.join(REPO_ROOT, rel);
  return fs.existsSync(abs) ? fs.readdirSync(abs, { withFileTypes: true }).filter((e) => e.isFile() && e.name.endsWith('.md')).map((e) => e.name).sort() : [];
}

/** Brain path -> candidate repository paths, for every template-owned file shipped today. */
function targets() {
  const map = {};
  for (const name of listDirs('templates/base/.agents/skills')) {
    if (!fs.existsSync(path.join(REPO_ROOT, 'templates/base/.agents/skills', name, 'SKILL.md'))) continue;
    map[`.agents/skills/${name}/SKILL.md`] = [
      `templates/base/.agents/skills/${name}/SKILL.md`, `templates/base/.agents/skills/${name}.md`,
      `.agents/skills/${name}/SKILL.md`, `.agents/skills/${name}.md`
    ];
  }
  for (const file of listMd('templates/base/skills')) map[`skills/${file}`] = [`templates/base/skills/${file}`, `skills/${file}`];
  map[MATRIX] = [`templates/areas/${MATRIX}`, ...listDirs('templates/locales').map((lang) => `templates/locales/${lang}/areas/${MATRIX}`)];
  return map;
}

/** Hashes of every committed version of `repoPath`, plus its working-tree version. */
function versions(repoPath) {
  const found = new Set();
  let commits = [];
  try {
    commits = git(['log', '--format=%H', '--', repoPath]).split('\n').filter(Boolean);
  } catch {
    // Not a git checkout: only the working tree is read.
  }
  for (const commit of commits) {
    try {
      found.add(hash(git(['show', `${commit}:${repoPath}`])));
    } catch {
      // The commit deleted the file.
    }
  }
  const abs = path.join(REPO_ROOT, repoPath);
  if (fs.existsSync(abs) && fs.statSync(abs).isFile()) found.add(hash(fs.readFileSync(abs, 'utf8')));
  return found;
}

function main() {
  const out = {};
  for (const [rel, sources] of Object.entries(targets()).sort(([a], [b]) => a.localeCompare(b))) {
    const all = new Set();
    for (const source of sources) for (const h of versions(source)) all.add(h);
    out[rel] = [...all].sort();
  }
  const body = `// Generated by tools/update-shipped-hashes.js — do not edit. Re-run it after changing a template-owned file.
// SHA-256 hashes (LF line endings) of every version this package shipped for each template-owned brain path.
// \`clc-brain upgrade\` replaces a brain file only when its hash is listed here; edited files are kept.

export const SHIPPED_HASHES = Object.freeze(${JSON.stringify(out, null, 2)});
`;
  fs.writeFileSync(OUT, body, 'utf8');
  const total = Object.values(out).reduce((n, list) => n + list.length, 0);
  console.log(`Wrote ${path.relative(REPO_ROOT, OUT)}: ${Object.keys(out).length} files, ${total} hashes.`);
}

main();
