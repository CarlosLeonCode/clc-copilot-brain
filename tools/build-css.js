#!/usr/bin/env node
/**
 * Build the CSS of the generated pages (`npm run build:css`).
 * Runs the Tailwind CLI (a devDependency) on src/core/styles/brain.css and writes the minified result, with a hash of
 * every input, to src/core/styles/compiled.js. That module is checked in and shipped, so installs never run Tailwind.
 * tests/page-css.test.js fails when an input changed without a rebuild, or when a rebuild gives different CSS.
 */
const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const STYLES_DIR = path.join(ROOT, 'src', 'core', 'styles');
const INPUT = path.join(STYLES_DIR, 'brain.css');
const OUTPUT = path.join(STYLES_DIR, 'compiled.js');
const SOURCE_DIRECTIVE = /^@source\s+"([^"]+)"\s*;/gm;
const BANNER_URL = /^\/\*!\s*(tailwindcss v[\d.]+ \| MIT License) \| https:\/\/tailwindcss\.com\s*\*\//;

const posix = (abs) => path.relative(ROOT, abs).split(path.sep).join('/');
const readText = (abs) => fs.readFileSync(abs, 'utf8').replace(/\r\n?/g, '\n');

/** The Tailwind input plus every file it scans for classes (its @source lines), as repo-relative paths. */
function inputFiles() {
  const css = readText(INPUT);
  const sources = [...css.matchAll(SOURCE_DIRECTIVE)].map((m) => path.resolve(STYLES_DIR, m[1]));
  return [INPUT, ...sources].map(posix);
}

/** The exact Tailwind version pinned in package.json devDependencies. */
function tailwindVersion() {
  const pkg = JSON.parse(readText(path.join(ROOT, 'package.json')));
  return `${pkg.devDependencies.tailwindcss}+cli@${pkg.devDependencies['@tailwindcss/cli']}`;
}

/** sha256 of the Tailwind version and every input file (path and content, line endings normalized). */
function sourceHash() {
  const hash = crypto.createHash('sha256');
  hash.update(`tailwind ${tailwindVersion()}\n`);
  for (const rel of inputFiles()) hash.update(`${rel}\n${readText(path.join(ROOT, rel))}\n`);
  return hash.digest('hex');
}

/** True when the Tailwind CLI is installed (devDependencies), so the CSS can be rebuilt here. */
function cliAvailable() {
  try {
    require.resolve('@tailwindcss/cli/package.json', { paths: [ROOT] });
    return true;
  } catch {
    return false;
  }
}

/** Run the Tailwind CLI and return the minified CSS, made safe to inline in an offline page. */
function compileCss() {
  const pkgPath = require.resolve('@tailwindcss/cli/package.json', { paths: [ROOT] });
  const cli = path.join(path.dirname(pkgPath), require(pkgPath).bin.tailwindcss);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'clc-brain-css-'));
  const out = path.join(dir, 'brain.css');
  try {
    execFileSync(process.execPath, [cli, '--input', INPUT, '--output', out, '--minify'], { cwd: ROOT, stdio: 'pipe' });
    const css = fs.readFileSync(out, 'utf8').trim().replace(BANNER_URL, '/*! $1 */');
    for (const [bad, why] of [[/https?:\/\//i, 'an external url'], [/url\(/i, 'a url('], [/@import/i, 'an @import'], [/<\/?style/i, 'a style tag'], [/<!--/, 'an html comment']]) {
      if (bad.test(css)) throw new Error(`The compiled CSS contains ${why}; pages must stay offline and self-contained.`);
    }
    return css;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

/** The source of src/core/styles/compiled.js. */
function moduleText(css, hash) {
  return [
    '// Generated by tools/build-css.js (`npm run build:css`) from src/core/styles/brain.css. Do not edit.',
    '// Inlined into every page clc-brain generates; see TECHNICAL.md ("Page styles") and ADR 0010.',
    `export const PAGE_CSS_SOURCE_HASH = '${hash}';`,
    `export const PAGE_CSS = ${JSON.stringify(css)};`,
    ''
  ].join('\n');
}

function main() {
  if (!cliAvailable()) {
    console.error('The Tailwind CLI is not installed. Run "npm install" (devDependencies) first.');
    process.exit(1);
  }
  const css = compileCss();
  fs.writeFileSync(OUTPUT, moduleText(css, sourceHash()));
  console.log(`Wrote ${posix(OUTPUT)} (${Buffer.byteLength(css)} bytes of CSS from ${inputFiles().length} files).`);
}

if (require.main === module) main();

module.exports = { OUTPUT, cliAvailable, compileCss, inputFiles, moduleText, sourceHash };
